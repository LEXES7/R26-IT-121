const BYTES = Uint8Array.from(atob(PACKED), (c) => c.charCodeAt(0))

/** Is there land at this coordinate? lon -180..180, lat -90..90. */
export function isLand(lon, lat) {
  const x = Math.min(359, Math.max(0, Math.floor(lon + 180)))
  const y = Math.min(179, Math.max(0, Math.floor(90 - lat)))
  const bit = y * 360 + x
  return (BYTES[bit >> 3] & (128 >> (bit & 7))) !== 0
}
